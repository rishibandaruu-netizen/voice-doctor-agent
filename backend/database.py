
import os
from datetime import datetime, timedelta

import psycopg
from dotenv import load_dotenv
from pathlib import Path

load_dotenv(Path(__file__).resolve().parent / ".env")


def get_connection():
    database_url = os.getenv("DATABASE_URL")

    if not database_url:
        raise RuntimeError("DATABASE_URL environment variable is missing.")

    return psycopg.connect(database_url)


def create_tables():
    conn = get_connection()

    try:
        with conn.cursor() as cursor:

            cursor.execute("""
                CREATE TABLE IF NOT EXISTS doctors (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name TEXT NOT NULL,
                    specialty TEXT NOT NULL
                )
            """)

            cursor.execute("""
                CREATE TABLE IF NOT EXISTS slots (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    doctor_id INTEGER REFERENCES doctors(id),
                    slot_time TEXT NOT NULL,
                    is_available BOOLEAN DEFAULT TRUE
                )
            """)

            cursor.execute("""
                CREATE TABLE IF NOT EXISTS appointments (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    patient_name TEXT,
                    phone TEXT NOT NULL,
                    doctor_id INTEGER REFERENCES doctors(id),
                    slot_id INTEGER REFERENCES slots(id),
                    status TEXT DEFAULT 'booked'
                )
            """)

        conn.commit()
        print("PostgreSQL tables created successfully!")

    except Exception:
        conn.rollback()
        raise

    finally:
        conn.close()


def insert_sample_data():
    conn = get_connection()

    try:
        with conn.cursor() as cursor:

            cursor.execute("SELECT COUNT(*) FROM doctors")
            count = cursor.fetchone()[0]

            if count == 0:
                doctors = [
                    ("Dr. Ananya", "Cardiologist"),
                    ("Dr. Rahul", "Dermatologist"),
                    ("Dr. Priya", "General Physician")
                ]

                doctor_ids = []

                for name, specialty in doctors:
                    cursor.execute("""
                        INSERT INTO doctors (name, specialty)
                        VALUES (%s, %s)
                        RETURNING id
                    """, (name, specialty))

                    doctor_ids.append(cursor.fetchone()[0])

                tomorrow = datetime.now() + timedelta(days=1)

                slots = []

                for doctor_id in doctor_ids:
                    for hour in [10, 11]:
                        slot_time = (
                            tomorrow.replace(
                                hour=hour,
                                minute=0,
                                second=0,
                                microsecond=0
                            )
                        )

                        slots.append(
                            (doctor_id, slot_time.strftime("%Y-%m-%d %I:%M %p"))
                        )

                cursor.executemany("""
                    INSERT INTO slots (doctor_id, slot_time)
                    VALUES (%s, %s)
                """, slots)

        conn.commit()
        print("Sample doctors and slots inserted successfully!")

    except Exception:
        conn.rollback()
        raise

    finally:
        conn.close()


if __name__ == "__main__":
    create_tables()
    insert_sample_data()
